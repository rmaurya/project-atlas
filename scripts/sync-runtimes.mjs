#!/usr/bin/env node
/**
 * project-atlas · runtime packaging
 *
 * `skills/` is the single source. Claude Code and Antigravity both read it in place — Claude via
 * `.claude-plugin/plugin.json`, Antigravity via the root `plugin.json` marker — so neither needs a copy.
 *
 * **Codex needs one, and only because of a marketplace rule.** A Codex marketplace resolves `source.path`
 * relative to the marketplace root and requires it to be a subdirectory: `"./"` is not accepted. So a
 * repository cannot be its own Codex plugin *entry* the way it can be its own Claude one, and
 * `plugins/atlas/` exists purely to satisfy that.
 *
 * A copy is a fork waiting to happen, which is the exact failure this project exists to detect. So:
 *
 *   node scripts/sync-runtimes.mjs           regenerate the Codex package
 *   node scripts/sync-runtimes.mjs --check   fail if it has drifted (CI, and the test suite)
 *
 * The generated tree is committed so an install works from a plain clone, and `--check` is what stops it
 * silently diverging from `skills/`.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'skills');
const CODEX = path.join(ROOT, 'plugins', 'atlas');

const check = process.argv.includes('--check');

const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, '.claude-plugin', 'plugin.json'), 'utf8'));

const codexManifest = {
  name: 'atlas',
  version: pkg.version,
  description: pkg.description,
  skills: './skills/',
  license: pkg.license,
  repository: pkg.repository,
  keywords: pkg.keywords,
  interface: {
    displayName: 'Project Atlas',
    shortDescription: 'A derived, auditable knowledgebase over your repository’s own documentation.',
    category: 'Productivity',
  },
};

const banner =
  '<!-- GENERATED by scripts/sync-runtimes.mjs from ../../skills/. Do not edit here — edit the source and\n' +
  '     re-run the script. `node scripts/sync-runtimes.mjs --check` fails if this has drifted. -->\n';

/** Every file the Codex package should contain, as path → contents. */
function desired() {
  const out = new Map();
  out.set('.codex-plugin/plugin.json', JSON.stringify(codexManifest, null, 2) + '\n');
  for (const name of fs.readdirSync(SRC).sort()) {
    const skill = path.join(SRC, name, 'SKILL.md');
    if (!fs.existsSync(skill)) continue;
    out.set(`skills/${name}/SKILL.md`, banner + fs.readFileSync(skill, 'utf8'));
  }
  return out;
}

function actual() {
  const out = new Map();
  const walk = (dir, base = '') => {
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p, base + e.name + '/');
      else out.set(base + e.name, fs.readFileSync(p, 'utf8'));
    }
  };
  walk(CODEX);
  return out;
}

const want = desired();
const have = actual();

const drift = [];
for (const [p, body] of want) {
  if (!have.has(p)) drift.push(`missing   ${p}`);
  else if (have.get(p) !== body) drift.push(`stale     ${p}`);
}
for (const p of have.keys()) if (!want.has(p)) drift.push(`orphaned  ${p}`);

if (check) {
  if (drift.length) {
    console.error(`The Codex package has drifted from skills/ (${drift.length}):\n  ` + drift.join('\n  '));
    console.error('\nRun: node scripts/sync-runtimes.mjs');
    process.exit(1);
  }
  console.log(`Codex package is in sync with skills/ (${want.size} file(s)).`);
  process.exit(0);
}

fs.rmSync(CODEX, { recursive: true, force: true });
for (const [p, body] of want) {
  const abs = path.join(CODEX, p);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, body, 'utf8');
}
console.log(`Wrote ${want.size} file(s) → plugins/atlas/`);
if (drift.length) for (const d of drift) console.log(`  ${d}`);
